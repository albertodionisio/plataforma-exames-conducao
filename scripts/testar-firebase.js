"use strict";
const fs = require("fs");
const vm = require("vm");
const assert = require("assert");
const configSource = fs.readFileSync("config.js", "utf8");
const context = { window: { location: { hostname: "plataforma-exames-conducao.vercel.app" } } };
vm.runInNewContext(configSource, context);
const app = context.window.APP;
assert(app && app.firebase, "Configuração Firebase em falta.");
["apiKey", "authDomain", "projectId", "appId"].forEach((key) => {
  assert(typeof app.firebase[key] === "string" && app.firebase[key].length > 0, "Campo Firebase inválido: " + key);
});
assert.strictEqual(app.firebase.projectId, "plataforma-exames-conducao");
assert.strictEqual(app.firebase.authDomain, "plataforma-exames-conducao.vercel.app");
const previewHost = "plataforma-exames-conducao-git-feat-firebase-full-preview.vercel.app";
const previewContext = { window: { location: { hostname: previewHost } } };
vm.runInNewContext(configSource, previewContext);
assert.strictEqual(previewContext.window.APP.firebase.authDomain, "plataforma-exames-conducao.firebaseapp.com", "Previews Vercel devem usar o domínio Firebase padrão para evitar callbacks OAuth únicos por deployment.");
const localContext = { window: { location: { hostname: "localhost" } } };
vm.runInNewContext(configSource, localContext);
assert.strictEqual(localContext.window.APP.firebase.authDomain, "plataforma-exames-conducao.firebaseapp.com", "Ambiente local deve usar o domínio Firebase padrão.");
assert.strictEqual(app.googleOAuthEnabled, true);
const html = fs.readFileSync("index.html", "utf8");
assert(html.includes("firebase-app-compat.js"), "SDK Firebase App não carregado.");
assert(html.includes("firebase-auth-compat.js"), "SDK Firebase Auth não carregado.");
assert(html.includes("firebase-firestore-compat.js"), "SDK Firestore não carregado.");
assert(!/supabase/i.test(html), "SDK Supabase ainda referenciado no HTML.");
const appJs = fs.readFileSync("app.js", "utf8");
assert(!/supabase/i.test(appJs), "Código Supabase ainda existe em app.js.");
["createUserWithEmailAndPassword", "sendEmailVerification", "signInWithEmailAndPassword",
 "sendPasswordResetEmail", "signInWithPopup", "signOut", "sincronizarPerfil"].forEach((needle) => {
  assert(appJs.includes(needle), "Fluxo Firebase em falta: " + needle);
});
assert(appJs.includes("/api/auth/phone"), "Endpoint de autenticação por telefone não integrado.");
assert(appJs.includes("signInWithCustomToken"), "Login com custom token não integrado.");
assert(appJs.includes("auth-confirm-password"), "Confirmação da palavra-passe em falta no registo por telefone.");
assert(appJs.includes("auth-identifier"), "Campo único de email ou telefone em falta.");
assert(appJs.includes("auth-first-name") && appJs.includes("auth-last-name"), "O registo deve pedir primeiro nome e sobrenome/apelido.");
assert(appJs.includes("var camposNome = registo"), "Os campos de nome devem aparecer apenas no registo.");
assert(appJs.includes("updateProfile({ displayName: displayName })"), "O nome deve ser associado ao perfil Firebase Auth.");
assert(appJs.includes("authDisplayName"), "O cabeçalho deve usar o nome guardado no perfil.");
assert(appJs.includes("/^\\+258(?:84|85|86|87|88)\\d{7}$/"), "Cliente deve aceitar apenas prefixos móveis moçambicanos de nove algarismos.");
assert(appJs.includes("/^\\d{9}$/"), "Cliente deve reconhecer números nacionais com exactamente nove algarismos.");
assert(!appJs.includes("/^\\\\d{9}$/"), "Não pode existir regex com barras duplicadas no reconhecimento do número.");

assert(appJs.includes("Email ou número de telefone"), "O campo deve identificar claramente os dois métodos.");
assert(!appJs.includes("Entrar ou criar conta com telefone"), "Não deve existir um atalho separado para login por telefone.");
assert(appJs.includes("return credential.user.sendEmailVerification();"), "A verificação deve usar o handler padrão Firebase, sem continue URL temporário.");
assert(appJs.includes("sendPasswordResetEmail(email).then"), "A recuperação deve usar o handler padrão Firebase, sem continue URL temporário.");
assert(!appJs.includes("sendEmailVerification({"), "Não enviar hostname Preview como continue URL de verificação.");
assert(!appJs.includes("sendPasswordResetEmail(email, {"), "Não enviar hostname Preview como continue URL de recuperação.");
assert(!appJs.includes("auth-method") && !appJs.includes("authMethod"), "Não deve existir alternância separada entre email e telefone.");
assert(appJs.includes('authMode === "registo" && password !== confirmar'),
  "A confirmação da palavra-passe deve aplicar-se ao registo com qualquer identificador.");
const phoneApi = fs.readFileSync("api/auth/phone.js", "utf8");
assert(phoneApi.includes("FIREBASE_SERVICE_ACCOUNT_JSON"), "Credencial Admin não documentada no backend.");
assert(phoneApi.includes("PHONE_AUTH_PEPPER"), "Segredo HMAC não configurado no backend.");
assert(phoneApi.includes("firstName") && phoneApi.includes("lastName") && phoneApi.includes("displayName"), "O backend de telefone deve guardar e devolver o nome do cadastro.");
assert(phoneApi.includes("body.firstName") && phoneApi.includes("body.lastName"), "O registo por telefone deve validar os campos de nome.");
const rules = fs.readFileSync("firestore.rules", "utf8");
assert(rules.includes("verifiedEmail()"), "As regras não exigem email verificado para escrever o perfil.");
assert(rules.includes("allow create, update, delete: if false;"), "As colecções protegidas devem bloquear escrita do cliente.");
const vercel = JSON.parse(fs.readFileSync("vercel.json", "utf8"));
assert(vercel.rewrites.some((r) => r.source === "/__/auth/:path*"), "Proxy Firebase Auth Vercel em falta.");
console.log("BE-002 Firebase: configuração, SDKs, autenticação, proxy e regras verificadas.");
